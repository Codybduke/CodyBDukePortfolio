/**
 * Bakes the stone's convex hull and resting framing into src/data/stone-hull.ts,
 * and the matching stage aspect into src/styles/stone.generated.css.
 *
 * The hull lets StoneHero re-fit the camera every frame from ~1.7k points
 * instead of 190k vertices, so the stone fills the frame at whatever pose it is
 * actually in rather than reserving room for its worst pose.
 *
 * Run with: npm run stone:hull
 */
import { writeFileSync } from 'node:fs';
import * as THREE from 'three';
import { ConvexHull } from 'three/examples/jsm/math/ConvexHull.js';
import {
  fitCamera,
  fitDistance,
  normalize,
  poseMatrix,
  projectedBounds,
  readGlbVertices,
} from './stone-geometry.mjs';

// Pose: a fixed 28deg clockwise tilt, spun about Y as the page scrolls.
const TILT_DEG = -28;
const SPIN_RAD = Math.PI * 1.15;
const FOV = 34;
const MARGIN = 1.02;
const TAN_V = Math.tan(((FOV * Math.PI) / 180) / 2);

const raw = await readGlbVertices(new URL('../public/models/stone.glb', import.meta.url));
const points = normalize(raw);

// `hull.vertices` is the full input list; the hull itself is described by its faces
const hull = new ConvexHull().setFromPoints(points);
const seen = new Set();
const hullPoints = [];
for (const face of hull.faces) {
  let edge = face.edge;
  do {
    const p = edge.head().point;
    if (!seen.has(p)) {
      seen.add(p);
      hullPoints.push(p.clone());
    }
    edge = edge.next;
  } while (edge !== face.edge);
}

console.log(`vertices ${raw.length} -> hull ${hullPoints.length}`);

const rest = poseMatrix(0, THREE.MathUtils.degToRad(TILT_DEG));
const restCloud = hullPoints.map((p) => p.clone().applyMatrix4(rest));

const frame = (aspect, offX, offY) => {
  const d = fitDistance(restCloud, { aspect, fov: FOV, margin: MARGIN, offX, offY });
  return { d, bounds: projectedBounds(restCloud, fitCamera(FOV, aspect, d), offX, offY) };
};

/*
 * Solve for the stage aspect ratio at which the resting stone touches all four
 * edges at once, plus the offset that centres it. Both converge together:
 * changing the aspect moves the camera, which moves the silhouette.
 */
let aspect = 0.75;
let offX = 0;
let offY = 0;
let converged = false;
for (let i = 0; i < 200 && !converged; i += 1) {
  const before = aspect;
  const { d, bounds } = frame(aspect, offX, offY);
  // Recentre: shift world-space by the NDC error scaled back to world units
  offX -= ((bounds.x0 + bounds.x1) / 2) * d * TAN_V * aspect;
  offY -= ((bounds.y0 + bounds.y1) / 2) * d * TAN_V;
  // Re-aim the aspect at the recentred silhouette's own ratio
  const centred = frame(aspect, offX, offY).bounds;
  aspect *= (centred.x1 - centred.x0) / (centred.y1 - centred.y0);
  converged = Math.abs(aspect - before) < 1e-9;
}
if (!converged) throw new Error('stage aspect did not converge in 200 iterations');

const { bounds } = frame(aspect, offX, offY);
console.log(
  `rest aspect ${aspect.toFixed(4)}  ` +
    `fills ${(((bounds.x1 - bounds.x0) / 2) * 100).toFixed(1)}% x ` +
    `${(((bounds.y1 - bounds.y0) / 2) * 100).toFixed(1)}% of frame`,
);

const flat = hullPoints.flatMap((p) => [p.x, p.y, p.z].map((n) => Number(n.toFixed(4))));

writeFileSync(
  new URL('../src/data/stone-hull.ts', import.meta.url),
  `// Generated by scripts/generate-stone-hull.mjs — do not edit by hand.
// Run \`npm run stone:hull\` after changing the model or the resting pose.

/** Fixed clockwise tilt, in degrees. */
export const STONE_TILT_DEG = ${TILT_DEG};

/** How far the stone spins about Y across a full page scroll, in radians. */
export const STONE_SPIN_RAD = ${SPIN_RAD};

/** Camera field of view the framing was solved for. */
export const STONE_FOV = ${FOV};

/** Safety margin applied to the fitted camera distance. */
export const STONE_FIT_MARGIN = ${MARGIN};

/**
 * Stage aspect ratio (w / h) at which the resting stone touches all four edges,
 * so the stage box and the stone's silhouette coincide. Emitted to CSS as
 * --stone-ratio in src/styles/stone.generated.css.
 */
export const STONE_ASPECT = ${aspect.toFixed(5)};

/** World-space offset applied after rotation to centre the resting silhouette. */
export const STONE_OFFSET: readonly [number, number] = [${offX.toFixed(5)}, ${offY.toFixed(5)}];

/** Convex hull of the normalised model, as flat xyz triples. */
export const STONE_HULL: readonly number[] = ${JSON.stringify(flat)};
`,
);

writeFileSync(
  new URL('../src/styles/stone.generated.css', import.meta.url),
  `/* Generated by scripts/generate-stone-hull.mjs — do not edit by hand. */
:root {
  /*
   * Aspect ratio at which the resting stone touches all four edges of its
   * stage, so the stage box and the stone's silhouette coincide and the hero
   * name and quote align to the stone itself rather than to empty space.
   */
  --stone-ratio: ${aspect.toFixed(5)};
}
`,
);

console.log('wrote src/data/stone-hull.ts and src/styles/stone.generated.css');
